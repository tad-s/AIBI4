def _parse_sql_master(path: str) -> dict[str, str]:
    if not os.path.exists(path):
        return {}
    sql = open(path, encoding="utf-8").read()
    pairs = re.findall(r"\('((?:[^']|'')*)'\s*,\s*'([^']+)'\s*,", sql)
    return {n.replace("''", "'"): c for n, c in pairs}


def build_master(sql_path: str | None = None) -> dict[str, str]:
    """SQLマスタ + PoC手当を統合（PoC手当を優先）。"""
    master: dict[str, str] = {}
    if sql_path:
        master.update(_parse_sql_master(sql_path))
    master.update(POC_OVERRIDES)   # PoC 手当を優先
    return master
